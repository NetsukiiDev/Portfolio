interface DatabaseText {
  title: string;
  subtitle: string;
  sqliteLabel: string;
  sqliteHint: string;
  mysqlLabel: string;
  mysqlHint: string;
  host: string;
  port: string;
  databaseName: string;
  user: string;
  password: string;
  testConnection: string;
  testing: string;
  connectionOk: string;
  continueLabel: string;
  committing: string;
  alreadyConfigured: string;
  next: string;
  genericError: string;
  connectionFailed: string;
  dbNotEmpty: string;
  missingField: (field: string) => string;
  fields: { host: string; port: string; database: string; user: string; password: string };
}

interface AccountText {
  title: string;
  subtitle: string;
  firstName: string;
  lastName: string;
  username: string;
  password: string;
  confirmPassword: string;
  required: string;
  minUsername: string;
  minPassword: string;
  passwordMismatch: string;
  back: string;
  continueLabel: string;
  creating: string;
  genericError: string;
}

interface SiteText {
  title: string;
  subtitle: string;
  domain: string;
  useHttps: string;
  domainHint: string;
  domainRequired: string;
  mainLanguage: string;
  theme: string;
  dark: string;
  light: string;
  back: string;
  finish: string;
  saving: string;
  genericError: string;
  tabs: { site: string; appearance: string; storage: string };
  palette: string;
  storageProvider: string;
  storageHint: string;
  storageLocal: string;
  storageS3: string;
  s3Endpoint: string;
  s3Region: string;
  s3Bucket: string;
  s3AccessKeyId: string;
  s3SecretAccessKey: string;
  s3PublicUrlBase: string;
  s3ForcePathStyle: string;
}

interface SetupText {
  stepper: { database: string; account: string; site: string };
  database: DatabaseText;
  account: AccountText;
  site: SiteText;
}

function fields(host: string, port: string, database: string, user: string, password: string) {
  return { host, port, database, user, password };
}

